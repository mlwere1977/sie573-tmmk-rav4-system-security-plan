#!/usr/bin/env python3
"""Summarize the selected NIST SP 800-53 Rev. 5 controls by family.

Reads data/ssp_controls_selection.csv (run export_controls.py first) and
prints a Markdown table: totals, baseline vs. added, OT overlay, control type,
and tailored vs. inherited designation per family.

Usage:
    python scripts/control_stats.py            # print to stdout
    python scripts/control_stats.py --write    # also write docs/control-statistics.md
"""
import csv
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "data/ssp_controls_selection.csv"
OUT_PATH = ROOT / "docs/control-statistics.md"

FAMILY_NAMES = {
    "AC": "Access Control", "AT": "Awareness and Training",
    "AU": "Audit and Accountability", "CA": "Assessment, Authorization, and Monitoring",
    "CM": "Configuration Management", "CP": "Contingency Planning",
    "IA": "Identification and Authentication", "IR": "Incident Response",
    "MA": "Maintenance", "MP": "Media Protection",
    "PE": "Physical and Environmental Protection", "PL": "Planning",
    "PS": "Personnel Security", "RA": "Risk Assessment",
    "SA": "System and Services Acquisition", "SC": "System and Communications Protection",
    "SI": "System and Information Integrity", "SR": "Supply Chain Risk Management",
}


def build() -> str:
    with CSV_PATH.open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    by_fam = defaultdict(list)
    for r in rows:
        by_fam[r["family"]].append(r)

    head = ("| Family | Name | Total | Moderate baseline | Added | OT overlay "
            "| Common | Hybrid | System | Tailored | Inherited |\n"
            "|---|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n")

    def line(label, name, rs):
        t = Counter(r["control_type"] for r in rs)
        ti = Counter(r["tailored_or_inherited"] for r in rs)
        base = sum(r["moderate_baseline"] == "yes" for r in rs)
        ot = sum(r["ot_overlay"] == "yes" for r in rs)
        return (f"| {label} | {name} | {len(rs)} | {base} | {len(rs) - base} | {ot} "
                f"| {t['Common']} | {t['Hybrid']} | {t['System']} "
                f"| {ti['Tailored']} | {ti['Inherited']} |\n")

    body = "".join(line(f, FAMILY_NAMES.get(f, ""), by_fam[f]) for f in sorted(by_fam))
    total = line("**All**", f"**{len(by_fam)} families**", rows)

    added = [r["control_id"] for r in rows if r["moderate_baseline"] == "no"]
    md = ("# Control Selection Statistics\n\n"
          "_Generated by `scripts/control_stats.py` from "
          "`data/ssp_controls_selection.csv`. Do not edit by hand._\n\n"
          + head + body + total +
          "\n**Controls added beyond the Moderate baseline:** "
          + ", ".join(f"`{c}`" for c in added) + "\n")
    return md


if __name__ == "__main__":
    md = build()
    print(md)
    if "--write" in sys.argv:
        OUT_PATH.write_text(md, encoding="utf-8")
        print(f"Wrote {OUT_PATH.relative_to(ROOT)}")
